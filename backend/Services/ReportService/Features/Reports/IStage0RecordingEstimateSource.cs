namespace ReportService.Features.Reports;

// FR-06, FR-15, ADR-0033 決定5・決定5.3, ADR-0037 決定3, #750, IADR-0254（追記）:
// 月報 §7 の対比列のうち、**見積り承認額**（分母側）の供給。
//
// 🔴 **本値は期間の集計ではない。** 実績（分子）は監査台帳の権威源から引くが（IADR-0254）、
// 承認額は**台帳に事象として載らない**——ADR-0033 決定5 の「承認」は利用者が実行前に構成へ書き入れる値であり
// （IADR-0318 決定5 は「構成値が算出した見積りと一致すること」で承認を表す）、イベントとして発生しない。
// したがって本供給だけは構成から読む。
//
// 🔴 **未供給（null）を 0 円へ倒さない。** 承認額 0 円は「0 円で承認された」であり、
// 未設定は「承認されていない／供給されていない」である。潰すと、承認が無いのに対比が成立して見える。
//
// 🔴 **記録側（取引判断サービス）へ HTTP で取りに行かない。** 同サービスの HTTP 面は無認可であり
// （IADR-0318 決定5「HTTP へは足さない」）、月報のために承認額の口をそこへ開けるのは主従が逆である。
public interface IStage0RecordingEstimateSource
{
    /// <summary>利用者が承認した Stage 0 記録実行の見積り額（円）。供給が無ければ null。</summary>
    decimal? GetApprovedEstimateJpy();
}
