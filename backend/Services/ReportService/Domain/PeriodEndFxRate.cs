namespace ReportService.Domain;

// FR-06, FR-16, #611, 05_trading-assumptions §3（為替評価方法: 評価損益＝日次終値）, IADR-0285 決定2:
// 為替差損益の**期末レート**。「期末日以前の直近の日次観測」であり、観測日を伴う。
//
// 日銀（17 時仲値）・FRED（NY 正午）はいずれも 1 日 1 値の日次系列で、収録は翌々営業日（日銀）／週次（FRED）である。
// したがって生成時点で得られる直近観測は期末日**以前**になり得る。**観測日を報告書に明記する**ことで、
// 「どの日の終値で再測定したか」を読み手が確かめられるようにする（推定値を実績として出さない）。
//
// 🔴 **観測日が期末日より後の読みは本型にならない**（供給側が null へ倒す）——後日のレートは期末レートではない。
public sealed record PeriodEndFxRate(decimal JpyPerUsd, DateOnly AsOf);
